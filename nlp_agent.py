FALLBACK = ("🤔 Я не впевнений, що правильно зрозумів запитання.<br>"
            "Спробуйте, наприклад: «куди викинути батарейку?», «скільки розкладається пластик?» "
            "або «навіщо сортувати сміття?».")


class IntentAgent:
    def __init__(self, threshold=0.40):
        self.threshold = threshold
        self.texts, self.labels = [], []
        for intent, phrases in TRAIN_DATA.items():
            for p in phrases:
                self.texts.append(p)
                self.labels.append(intent)

        self.pipeline = make_pipeline(
            TfidfVectorizer(analyzer="char_wb", ngram_range=(2, 5),
                            lowercase=True, sublinear_tf=True),
            LogisticRegression(C=20, max_iter=2000),
        )
        self.pipeline.fit(self.texts, self.labels)

    def evaluate(self):
        """5-кратна крос-валідація: (accuracy %, кількість фраз, кількість намірів)."""
        cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
        scores = cross_val_score(self.pipeline, self.texts, self.labels, cv=cv)
        return float(scores.mean() * 100), len(self.texts), len(set(self.labels))

    def predict(self, query):
        probs = self.pipeline.predict_proba([query])[0]
        idx = int(np.argmax(probs))
        return str(self.pipeline.classes_[idx]), float(probs[idx])

    def reply(self, query, class_info):
        intent, conf = self.predict(query)
        if conf < self.threshold:
            return FALLBACK + f"<br><br><i>🔎 Найближчий намір: {intent}, впевненість {conf:.0%}</i>"

        if intent in MATERIAL_INTENTS:
            material, bin_, decomp, desc = class_info[intent]
            body = (f"<b>{material}</b><br><br>"
                    f"🗑️ <b>Куди:</b> {bin_}<br>"
                    f"⏳ <b>Розкладання:</b> {decomp}<br>"
                    f"💡 {desc}")
        elif intent == "time_general":
            lines = "".join(f"• {v[0]}: {v[2]}<br>" for v in class_info.values())
            body = "⏳ <b>Орієнтовні терміни розкладання:</b><br>" + lines
        elif intent == "bins_general":
            by_bin = {}
            for v in class_info.values():
                by_bin.setdefault(v[1], []).append(v[0])
            lines = "".join(f"• <b>{b}:</b> {', '.join(m)}<br>" for b, m in by_bin.items())
            body = "🗂️ <b>Який контейнер для чого:</b><br>" + lines
        else:
            body = GENERAL_ANSWERS[intent]

        return body + f"<br><br><i>🔎 Намір: {intent} · впевненість {conf:.0%}</i>"
